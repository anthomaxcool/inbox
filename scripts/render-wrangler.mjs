#!/usr/bin/env node
// Renders src/<worker>/wrangler.template.jsonc → src/<worker>/wrangler.jsonc (git-ignored) from
// build variables (plan §8.12): INBOX_D1_ID, INBOX_R2_BUCKET, APP_HOST, AGENT_HOST, MAILBOX.
// Usage: node scripts/render-wrangler.mjs <mail|app>
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const VARS = ['INBOX_D1_ID', 'INBOX_R2_BUCKET', 'APP_HOST', 'AGENT_HOST', 'MAILBOX'];
const CHECKS = {
	INBOX_D1_ID: /^[0-9a-f-]{32,36}$/i,
	INBOX_R2_BUCKET: /^[a-z0-9][a-z0-9-]{1,61}[a-z0-9]$/,
	APP_HOST: /^[a-z0-9.-]+(:\d+)?$/i,
	AGENT_HOST: /^[a-z0-9.-]+(:\d+)?$/i,
	MAILBOX: /^[^\s@"]+@[a-z0-9.-]+$/i
};
// What a valid value looks like. The error never echoes the value itself, since build logs are kept.
const HOST_HINT = 'a bare hostname like inbox.example.com, with no https://, no path and no trailing /';
const HINTS = {
	INBOX_D1_ID: 'the Database ID from the D1 page, like 0a1b2c3d-...',
	INBOX_R2_BUCKET: 'the bucket name: lowercase letters, digits and dashes',
	APP_HOST: HOST_HINT,
	AGENT_HOST: HOST_HINT,
	MAILBOX: 'one address like support@example.com'
};

export function render(template, vars) {
	return template.replace(/\$\{([A-Z0-9_]+)\}/g, (_m, name) => {
		if (!VARS.includes(name)) throw new Error(`unknown template variable ${name}`);
		// Surrounding whitespace is a paste artefact, never part of a valid value.
		const value = (vars[name] ?? '').trim();
		if (!value) throw new Error(`missing build variable ${name}`);
		if (!CHECKS[name].test(value)) throw new Error(`build variable ${name} has an unexpected format. Expected ${HINTS[name]}.`);
		return value;
	});
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
	const worker = process.argv[2];
	if (worker !== 'mail' && worker !== 'app') {
		console.error('usage: render-wrangler.mjs <mail|app>');
		process.exit(2);
	}
	const dir = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', worker);
	try {
		const out = render(readFileSync(join(dir, 'wrangler.template.jsonc'), 'utf8'), process.env);
		writeFileSync(join(dir, 'wrangler.jsonc'), `// GENERATED by scripts/render-wrangler.mjs. Do not commit.\n${out}`);
		console.log(`rendered src/${worker}/wrangler.jsonc`);
	} catch (err) {
		console.error(err.message);
		process.exit(1);
	}
}
